const String kIrodoriBatchWorkerScript = r'''
"""Fushi Irodori batch worker (generated by the Fushi app; edits are overwritten).

Reads one JSON request per stdin line and writes protocol events to stdout as
"@@fushi <json>" lines. Everything else on stdout/stderr is log output.

Requests:
  {"op": "synthesize", "job": str, "items": [item, ...]}
  {"op": "cancel", "job": str}
  {"op": "shutdown"}
item:
  {"id": str, "text": str, "refs": [path, ...], "adapter": path|null,
   "seconds": float|null, "seed": int, "steps": int, "cfg_text": float,
   "cfg_speaker": float, "caption": str?, "duration_scale": float?,
   "out": path}
  caption is the Voice Design caption (per-line emotion / delivery; v4 models
  combine it with the reference audio). duration_scale scales the predicted
  duration (speaking rate); both are omitted when unused.
Events:
  loading {stage}; ready {protocol, device}; line {job, id, index, total, ok,
  out?, duration_ms?, error?}; job_done {job, ok, failed, cancelled};
  fatal {error}
"""
from __future__ import annotations

import argparse
import dataclasses
import json
import os
import queue
import struct
import sys
import threading
import time
import traceback

PROTOCOL = 2
PREFIX = "@@fushi "

os.environ.setdefault("IRODORI_SDPA_CUDNN", "0")

_out_lock = threading.Lock()


def emit(event: str, **fields: object) -> None:
    fields["event"] = event
    line = PREFIX + json.dumps(fields, ensure_ascii=False)
    with _out_lock:
        sys.stdout.write(line + "\n")
        sys.stdout.flush()


def log(message: str) -> None:
    with _out_lock:
        sys.stderr.write(message + "\n")
        sys.stderr.flush()


def install_low_memory_loader(rt, torch) -> None:
    """Plain-IO safetensors reader (1x commit charge instead of mmap + copy)."""
    dtypes = {
        "F64": torch.float64, "F32": torch.float32, "F16": torch.float16,
        "BF16": torch.bfloat16, "I64": torch.int64, "I32": torch.int32,
        "I16": torch.int16, "I8": torch.int8, "U8": torch.uint8,
        "BOOL": torch.bool,
    }
    for name in ("float8_e4m3fn", "float8_e5m2"):
        if hasattr(torch, name):
            dtypes["F8_E4M3" if name.endswith("e4m3fn") else "F8_E5M2"] = getattr(torch, name)

    def load_no_mmap(path, device="cpu"):
        out = {}
        with open(path, "rb", buffering=0) as f:
            (hlen,) = struct.unpack("<Q", f.read(8))
            header = json.loads(f.read(hlen))
            base = 8 + hlen
            header.pop("__metadata__", None)
            for name, info in sorted(header.items(), key=lambda kv: kv[1]["data_offsets"][0]):
                start, end = info["data_offsets"]
                t = torch.empty(info["shape"], dtype=dtypes[info["dtype"]])
                if t.numel() * t.element_size() != end - start:
                    raise IOError(f"size mismatch for {name}")
                if t.numel():
                    buf = t.view(-1).view(torch.uint8).numpy()
                    f.seek(base + start)
                    mv, got = memoryview(buf), 0
                    while got < len(mv):
                        n = f.readinto(mv[got:])
                        if not n:
                            raise IOError(f"short read for {name}")
                        got += n
                out[name] = t if device == "cpu" else t.to(device)
        return out

    class HeaderOnlySafeOpen:
        """safe_open stand-in for metadata reads (avoids a second full mapping)."""

        def __init__(self, path, framework="pt", device="cpu"):
            with open(path, "rb") as f:
                (hlen,) = struct.unpack("<Q", f.read(8))
                self._meta = json.loads(f.read(hlen)).get("__metadata__")

        def __enter__(self):
            return self

        def __exit__(self, *exc):
            return None

        def metadata(self):
            return self._meta

    rt.load_safetensors_file = load_no_mmap
    rt.safe_open = HeaderOnlySafeOpen


def apply_sdpa_switch() -> None:
    if os.environ.get("IRODORI_SDPA_CUDNN", "").strip() != "0":
        return
    try:
        import irodori_tts.attention as attention
        from torch.nn.attention import SDPBackend
    except Exception:  # noqa: BLE001 - optional speed-up only
        return
    if hasattr(attention, "_sdpa_priority"):
        return  # upstream honours the variable itself
    priority = getattr(attention, "_SDPA_PRIORITY", None)
    if isinstance(priority, list) and SDPBackend.CUDNN_ATTENTION in priority:
        priority.remove(SDPBackend.CUDNN_ATTENTION)  # in place: read at call time


def pick_device(torch, requested: str) -> str:
    if requested != "auto":
        return requested
    if torch.cuda.is_available():
        return "cuda"
    mps = getattr(torch.backends, "mps", None)
    if mps is not None and mps.is_available():
        return "mps"
    return "cpu"


def runtime_key(RuntimeKey, **values):
    """Only pass fields this irodori_tts version knows (the dataclass grows over time)."""
    known = {f.name for f in dataclasses.fields(RuntimeKey)}
    return RuntimeKey(**{k: v for k, v in values.items() if k in known})


def sampling_request(SamplingRequest, **values):
    known = {f.name for f in dataclasses.fields(SamplingRequest)}
    return SamplingRequest(**{k: v for k, v in values.items() if k in known})


def detach_stdin():
    """Moves the request pipe off fd 0 / STD_INPUT_HANDLE and returns it.

    On Windows a synchronous ReadFile pending on a pipe blocks every other call
    on that handle (GetFileType, DuplicateHandle). Each native DLL with its own
    CRT probes the std handles while loading, and subprocess duplicates
    STD_INPUT_HANDLE, so a reader thread parked on the real stdin deadlocks
    `import torch` (numpy's extension module never finishes loading). The
    reader gets a private, non-inheritable duplicate; fd 0 (and, through dup2,
    STD_INPUT_HANDLE) points at the null device.
    """
    fd = os.dup(0)
    null = os.open(os.devnull, os.O_RDONLY)
    try:
        os.dup2(null, 0)
    finally:
        os.close(null)
    sys.stdin = open(os.devnull, "r", encoding="utf-8")
    return os.fdopen(fd, "r", encoding="utf-8")


class Reader(threading.Thread):
    """Reads requests so a cancel arrives while a job is running."""

    def __init__(self, source) -> None:
        super().__init__(daemon=True)
        self.source = source
        self.requests: queue.Queue = queue.Queue()
        self.cancelled: set[str] = set()
        self.lock = threading.Lock()

    def run(self) -> None:
        for raw in self.source:
            raw = raw.strip()
            if not raw:
                continue
            try:
                req = json.loads(raw)
            except ValueError:
                log(f"bad request line: {raw[:120]}")
                continue
            if req.get("op") == "cancel":
                with self.lock:
                    self.cancelled.add(str(req.get("job")))
                continue
            self.requests.put(req)
        self.requests.put({"op": "shutdown"})  # parent went away

    def is_cancelled(self, job: str) -> bool:
        with self.lock:
            return job in self.cancelled


def run_job(runtime, save_wav, SamplingRequest, reader: Reader, req: dict) -> None:
    job = str(req.get("job"))
    items = req.get("items") or []
    total = len(items)
    ok = failed = 0
    cancelled = False
    for index, item in enumerate(items):
        if reader.is_cancelled(job):
            cancelled = True
            break
        line_id = str(item.get("id"))
        out = str(item.get("out"))
        t0 = time.time()
        try:
            res = runtime.synthesize(sampling_request(
                SamplingRequest,
                text=item["text"],
                ref_wavs=list(item.get("refs") or []) or None,
                no_ref=not item.get("refs"),
                num_steps=int(item.get("steps", 40)),
                cfg_scale_text=float(item.get("cfg_text", 3.0)),
                cfg_scale_speaker=float(item.get("cfg_speaker", 5.0)),
                seed=int(item.get("seed", 0)),
                seconds=item.get("seconds"),
                caption=item.get("caption") or None,
                duration_scale=float(item.get("duration_scale") or 1.0),
                lora_adapter=item.get("adapter") or None,
            ))
            os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
            stem, ext = os.path.splitext(out)
            tmp = f"{stem}.partial{ext or '.wav'}"
            save_wav(tmp, res.audio, res.sample_rate)
            os.replace(tmp, out)
            duration_ms = int(round(res.audio.shape[-1] * 1000 / res.sample_rate))
            ok += 1
            emit("line", job=job, id=line_id, index=index, total=total, ok=True,
                 out=out, duration_ms=duration_ms,
                 elapsed_ms=int((time.time() - t0) * 1000))
        except Exception as e:  # noqa: BLE001 - report the line, keep the batch going
            failed += 1
            emit("line", job=job, id=line_id, index=index, total=total, ok=False,
                 error=f"{type(e).__name__}: {str(e)[:300]}")
    with reader.lock:
        reader.cancelled.discard(job)
    emit("job_done", job=job, ok=ok, failed=failed, cancelled=cancelled)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--checkpoint", required=True)
    parser.add_argument("--codec", required=True)
    parser.add_argument("--device", default="auto")
    parser.add_argument("--precision", default="fp32")
    args = parser.parse_args()

    reader = Reader(detach_stdin())
    reader.start()
    try:
        emit("loading", stage="import")
        import torch
        import irodori_tts.inference_runtime as rt
        from irodori_tts.inference_runtime import InferenceRuntime, RuntimeKey, SamplingRequest, save_wav

        install_low_memory_loader(rt, torch)
        apply_sdpa_switch()
        device = pick_device(torch, args.device)
        emit("loading", stage="model")
        runtime = InferenceRuntime.from_key(runtime_key(
            RuntimeKey,
            checkpoint=args.checkpoint, model_device=device, codec_repo=args.codec,
            model_precision=args.precision, codec_device=device, codec_precision=args.precision,
            codec_deterministic_encode=True, codec_deterministic_decode=True,
            compile_model=False, compile_dynamic=False, split_rare_tokens=False))
    except BaseException as e:  # noqa: BLE001 - MemoryError, missing deps, CUDA errors
        traceback.print_exc()
        emit("fatal", error=f"{type(e).__name__}: {str(e)[:300]}")
        return 1
    emit("ready", protocol=PROTOCOL, device=device)

    while True:
        req = reader.requests.get()
        op = req.get("op")
        if op == "shutdown":
            return 0
        if op == "synthesize":
            run_job(runtime, save_wav, SamplingRequest, reader, req)
        else:
            log(f"unknown op: {op}")


if __name__ == "__main__":
    sys.exit(main())
''';
