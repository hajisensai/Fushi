/// 批处理 worker 的 Python 源码（随 app 发布，启动前写进 Irodori 安装目录的
/// `worker/` 下，由安装好的 `.venv` 解释器跑）。协议见 `irodori_batch_worker.dart`。
///
/// 行为对齐应用外参考实现（所有者本机的 `eval/manga_vol2/generate.py`）：
/// - 底模只加载一次；读 safetensors 用普通文件 IO 读进预分配内存（Windows 上默认的
///   内存映射加载 13 GB 需要约两倍提交内存，内存紧张时会在加载中途崩）；
/// - `IRODORI_SDPA_CUDNN=0`（cuDNN 每遇到新形状都要建执行计划，变长推理约慢 4 倍）。
///   上游较新的 `attention.py` 认这个变量；钉死的版本还没有，就由 worker 自己把
///   cuDNN 从 SDPA 优先级里拿掉，效果相同；
/// - 每句单独 try：一句失败只回报这一句，整批继续；
/// - 按调用方给的顺序合成（Dart 侧已按「LoRA → 参考音频组」排好，adapter 只切换一次）。
