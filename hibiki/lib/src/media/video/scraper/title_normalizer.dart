/// 标题归一化（刮削流水线第③层）。
///
/// 把来自文件名解析层与各数据源的标题拉到同一比较平面：
/// 全角→半角、繁（含日文旧字体/新字体变体）→简、小写化、
/// 去装饰符号、连续空白折叠；并提供分词与相似度计算。
///
/// 纯静态工具类，无状态、无 IO、无用户可见字符串。
library;

import 'dart:math' as math;

/// 标题归一化与相似度工具。
class TitleNormalizer {
  const TitleNormalizer._();

  /// 归一化：全角→半角 → 繁→简 → 小写 → 去装饰符号（替换为空格）→ 空白折叠。
  ///
  /// 装饰符号替换为空格而不是直接删除，避免把本不相邻的两段文字
  /// 粘连成一个假词（如 `A～B` 变 `ab`）；随后统一折叠空白。
  static String normalize(String title) {
    final StringBuffer buffer = StringBuffer();
    for (final int rune in title.runes) {
      int r = rune;
      // 全角空格 → 半角空格。
      if (r == 0x3000) {
        r = 0x20;
      } else if (r >= 0xFF01 && r <= 0xFF5E) {
        // 全角 ASCII 区（！Ａ１：等）整段平移到半角。
        r = r - 0xFEE0;
      }
      // 繁体/日文变体 → 简体（单字映射，覆盖动画标题高频字）。
      final String ch = String.fromCharCode(r);
      final String simplified = _kTraditionalToSimplified[ch] ?? ch;
      // 装饰符号 → 空格。
      if (simplified.length == 1 &&
          _kDecorationChars.contains(simplified.codeUnitAt(0))) {
        buffer.write(' ');
      } else {
        buffer.write(simplified);
      }
    }
    // 小写化 + 空白折叠。
    return buffer
        .toString()
        .toLowerCase()
        .replaceAll(RegExp(r'\s+'), ' ')
        .trim();
  }

  /// 分词（输入应为 [normalize] 的输出）：
  /// - ASCII/其它字母数字连续段整体为一个 token（按空白与分隔天然切开）；
  /// - CJK（汉字/假名）连续段按 2-gram 切——中文日文无空格分界，
  ///   bigram 是无词典条件下最稳的相似度基元；
  /// - 长度为 1 的 CJK 段保留原字。
  static List<String> tokens(String normalized) {
    final List<String> result = <String>[];
    final List<int> runes = normalized.runes.toList();
    int i = 0;
    while (i < runes.length) {
      final int r = runes[i];
      if (_isCjk(r)) {
        // 收集连续 CJK 段。
        int j = i;
        while (j < runes.length && _isCjk(runes[j])) {
          j++;
        }
        final int len = j - i;
        if (len == 1) {
          result.add(String.fromCharCode(runes[i]));
        } else {
          for (int k = i; k + 1 < j; k++) {
            result.add(String.fromCharCodes(<int>[runes[k], runes[k + 1]]));
          }
        }
        i = j;
      } else if (_isWordChar(r)) {
        // 收集连续字母/数字段（含罗马数字 ⅱ 等非 ASCII 字母）。
        int j = i;
        while (j < runes.length && _isWordChar(runes[j]) && !_isCjk(runes[j])) {
          j++;
        }
        result.add(String.fromCharCodes(runes.sublist(i, j)));
        i = j;
      } else {
        i++; // 分隔符（空格等）跳过。
      }
    }
    return result;
  }

  /// 相似度 [0,1]：先各自 [normalize]，再取
  /// token 集 Dice 系数与归一化 Levenshtein 相似度（1 - dist/maxLen）的较大者。
  ///
  /// Dice 抗子串/词序差异，Levenshtein 抗少量错字；取 max 兼顾两类失真。
  static double similarity(String a, String b) {
    final String na = normalize(a);
    final String nb = normalize(b);
    if (na.isEmpty || nb.isEmpty) {
      return na == nb ? 1.0 : 0.0;
    }
    if (na == nb) {
      return 1.0;
    }
    final Set<String> ta = tokens(na).toSet();
    final Set<String> tb = tokens(nb).toSet();
    double dice = 0.0;
    if (ta.isNotEmpty && tb.isNotEmpty) {
      final int inter = ta.intersection(tb).length;
      dice = 2.0 * inter / (ta.length + tb.length);
    }
    final int dist = _levenshtein(na, nb);
    final int maxLen = math.max(na.length, nb.length);
    final double lev = maxLen == 0 ? 1.0 : 1.0 - dist / maxLen;
    return math.max(dice, math.max(lev, 0.0));
  }

  /// 判定是否 CJK（汉字 + 平/片假名；假名同样无空格分界，一并 bigram）。
  static bool _isCjk(int rune) {
    return (rune >= 0x4E00 && rune <= 0x9FFF) || // CJK 统一表意文字
        (rune >= 0x3400 && rune <= 0x4DBF) || // 扩展 A
        (rune >= 0xF900 && rune <= 0xFAFF) || // 兼容表意文字
        (rune >= 0x3040 && rune <= 0x309F) || // 平假名
        (rune >= 0x30A0 && rune <= 0x30FF); // 片假名（含 ー）
  }

  /// 字母/数字（Unicode 视角，覆盖罗马数字 Ⅱ/ⅱ 等）。
  static bool _isWordChar(int rune) {
    if ((rune >= 0x30 && rune <= 0x39) ||
        (rune >= 0x41 && rune <= 0x5A) ||
        (rune >= 0x61 && rune <= 0x7A)) {
      return true;
    }
    if (rune >= 0x2160 && rune <= 0x217F) {
      return true; // 罗马数字区
    }
    if (_isCjk(rune)) {
      return true;
    }
    // 其它非 ASCII 字母（带音标拉丁、希腊、西里尔等）。
    if (rune > 0x7F) {
      final String s = String.fromCharCode(rune);
      return s.toLowerCase() != s.toUpperCase() ||
          RegExp(r'\p{L}|\p{N}', unicode: true).hasMatch(s);
    }
    return false;
  }

  /// 经典两行滚动 Levenshtein，O(n*m) 时间 O(min) 空间。
  static int _levenshtein(String a, String b) {
    final List<int> ra = a.runes.toList();
    final List<int> rb = b.runes.toList();
    if (ra.isEmpty) return rb.length;
    if (rb.isEmpty) return ra.length;
    List<int> prev =
        List<int>.generate(rb.length + 1, (int i) => i, growable: false);
    List<int> curr = List<int>.filled(rb.length + 1, 0, growable: false);
    for (int i = 1; i <= ra.length; i++) {
      curr[0] = i;
      for (int j = 1; j <= rb.length; j++) {
        final int cost = ra[i - 1] == rb[j - 1] ? 0 : 1;
        curr[j] = math.min(
          math.min(curr[j - 1] + 1, prev[j] + 1),
          prev[j - 1] + cost,
        );
      }
      final List<int> tmp = prev;
      prev = curr;
      curr = tmp;
    }
    return prev[rb.length];
  }
}

/// 装饰符号集合（归一化后按半角判断；替换为空格再折叠）。
/// 注意不含 CJK 长音符「ー」（是词的一部分）与罗马数字（用于季度识别）。
final Set<int> _kDecorationChars = <int>{
  // ASCII 标点（全角经平移后也落在这里）。
