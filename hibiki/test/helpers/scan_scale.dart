import 'package:flutter_test/flutter_test.dart';

/// 目录枚举型守卫的**扫描规模哨兵**（TODO-2707）。
///
/// 这批守卫（30+ 条）都是同一个形状：枚举某个源码树 → 逐文件匹配 → 断言「没有违规」。
/// 它们有一个共同的、系统性的假绿源：
///
/// 🔴 **「扫不到任何文件」和「扫到了但没有违规」在断言层面长得一模一样，都是绿。**
///
/// 目录改名、包重构、路径常量写错、过滤条件写反、`dart format` 改了写法让匹配失效、
/// 工作目录不是 `hibiki/`——全都会让守卫静默退化成「永远绿」。而且**没有人会发现**，
/// 因为它本来就一直是绿的。守卫越多，这种「全绿」越不值钱。
///
/// 所以每条目录枚举型守卫都必须显式声明「这一轮确实扫到了多少东西」。
///
/// ## 为什么是下界，不是等值
///
/// 等值（`expect(count, 939)`）每加删一个文件就红一次，是纯噪音；噪音守卫的下场是被
/// 人删掉，删掉之后连下界都没有了。下界只在**量级塌掉**时才响，平时零维护。
///
/// ## 为什么下界不能是 `isNotEmpty` / `greaterThan(0)`
///
/// 一条本该扫 939 个文件的守卫扫出 1 个，显然是坏的——但 `isNotEmpty` 照样放行。
/// 哨兵要钉住**量级**，不是钉住非空。本函数因此**拒绝** [atLeast] < 2 的调用。
///
/// ## 参数怎么定
///
/// - [measured]：写下这条哨兵时**实测**的真实数量（留作后人判断「现在掉了多少」的基准）。
/// - [atLeast]：取 [measured] 的约 80%，向下取整到一个好记的数。
///
/// **什么时候该调 [atLeast]**：只有真的把那棵树删到下界以下（大规模删文件 / 拆包）才调。
/// 因为「扫描根改名、过滤写错」而红的时候，要修的是扫描逻辑，**不是**把这个数改小——
/// 把数改小就是把守卫重新弄瞎。
void expectScanScale(
  int scanned, {
  required String what,
  required int atLeast,
  required int measured,
}) {
  assert(atLeast >= 2, '哨兵下界必须钉量级；`>= 1` 等同于 isNotEmpty，挡不住塌陷');
  expect(
    scanned,
    greaterThanOrEqualTo(atLeast),
    reason: '扫描规模哨兵：$what 只扫到 $scanned 个，下界是 $atLeast'
        '（写下这条哨兵时实测 $measured 个）。\n'
        '这几乎一定是**守卫自己坏了**而不是代码变干净了：扫描根改名 / 路径常量写错 / '
        '过滤条件写反 / 工作目录不是 hibiki/ 都长这样。\n'
        '先去修扫描逻辑；除非真把那棵树删到了 $atLeast 以下，否则**不要**把下界改小——'
        '改小就是把守卫重新弄瞎，而瞎掉的守卫表现为永远绿。',
  );
}
