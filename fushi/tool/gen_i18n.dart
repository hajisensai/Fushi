// Generates fushi/lib/i18n/strings.g.dart from the 17 i18n json files.
//
//   dart fushi/tool/gen_i18n.dart [--force]      (from any directory)
//
// strings.g.dart is NOT tracked in git (37 MB, rewritten by every key change);
// every place that analyzes, tests or builds the app runs this first, after
// pub get: tool/bootstrap.ps1, tool/bootstrap.sh, the melos bootstrap post
// hook, fushi/tool/dist_test/worker_prepare.sh, the .github/actions/gen-i18n
// composite action in each CI job that compiles the app, fushi/tool/heavy.dart
// before a local analyze / test / build in fushi/, and the post-checkout /
// post-merge git hooks tool/git_hooks/install.sh installs (guard:
// fushi/test/build/strings_g_dart_untracked_guard_test.dart).
//
// Output is `dart run slang` + `dart format` of that one file — byte-identical
// to what used to be committed. A stamp in fushi/.dart_tool keyed by every
// input (slang.yaml, the json files, the lockfile that pins slang, the Dart
// SDK that formats, this script) plus the output's own hash makes a repeat run
// a no-op; any change to inputs, a missing output or a hand-edited output
// regenerates it.
import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';

const String _stampName = 'fushi_gen_i18n.stamp';
const String _output = 'lib/i18n/strings.g.dart';

Future<void> main(List<String> args) async {
  final bool force = args.contains('--force');
  final List<String> unknown = args
      .where((String a) => a != '--force')
      .toList();
  if (unknown.isNotEmpty) {
    stderr.writeln('usage: dart fushi/tool/gen_i18n.dart [--force]');
    exit(64);
  }

  final Directory app = fushiAppDir();
  final File output = File('${app.path}/$_output');
  final File stamp = File('${app.path}/.dart_tool/$_stampName');
  final String inputs = inputsHash(app);

  if (!force && output.existsSync() && stamp.existsSync()) {
    final Object? saved = _tryDecode(stamp.readAsStringSync());
    if (saved is Map &&
        saved['inputs'] == inputs &&
        saved['output'] == _fileHash(output)) {
      stdout.writeln('gen_i18n: $_output up to date');
      return;
    }
  }

  final Stopwatch watch = Stopwatch()..start();
  // The Dart executable running this script: the same SDK pub get used.
  final String dart = Platform.resolvedExecutable;
  await _run(dart, <String>['run', 'slang'], app);
  await _run(dart, <String>['format', _output], app);
  if (!output.existsSync()) {
    stderr.writeln('gen_i18n: slang reported success but wrote no $_output');
    exit(1);
  }
  stamp.parent.createSync(recursive: true);
  stamp.writeAsStringSync(
    jsonEncode(<String, String>{'inputs': inputs, 'output': _fileHash(output)}),
  );
  stdout.writeln('gen_i18n: generated $_output in ${watch.elapsed.inSeconds}s');
}

/// fushi/ (the app package), from this script's location.
Directory fushiAppDir() {
  final File script = File.fromUri(Platform.script);
  return script.parent.parent.absolute;
}

/// Hash over everything that decides the generated bytes.
String inputsHash(Directory app) {
  final List<File> files = <File>[
    File('${app.path}/slang.yaml'),
    File('${app.path}/../pubspec.lock'),
    File('${app.path}/tool/gen_i18n.dart'),
    ...Directory('${app.path}/lib/i18n')
        .listSync()
        .whereType<File>()
        .where((File f) => f.path.endsWith('.i18n.json'))
        .toList()
      ..sort((File a, File b) => a.path.compareTo(b.path)),
  ];
  final AccumulatorSink<Digest> sink = AccumulatorSink<Digest>();
  final ByteConversionSink input = sha256.startChunkedConversion(sink);
  input.add(utf8.encode('dart ${Platform.version}\n'));
  for (final File f in files) {
    if (!f.existsSync()) {
      stderr.writeln('gen_i18n: missing input ${f.path}');
      exit(1);
    }
    final String name = f.uri.pathSegments.last;
    input.add(utf8.encode('$name\n'));
    input.add(f.readAsBytesSync());
  }
  input.close();
  return sink.events.single.toString();
}

String _fileHash(File f) => sha256.convert(f.readAsBytesSync()).toString();

Object? _tryDecode(String s) {
  try {
    return jsonDecode(s);
  } on FormatException {
    return null;
  }
}

Future<void> _run(String exe, List<String> args, Directory cwd) async {
  final Process p = await Process.start(
    exe,
    args,
    workingDirectory: cwd.path,
    mode: ProcessStartMode.inheritStdio,
  );
  final int code = await p.exitCode;
  if (code != 0) {
    stderr.writeln('gen_i18n: `dart ${args.join(' ')}` failed (exit $code)');
    exit(code);
  }
}

/// A sink that collects what a chunked hash emits (package:convert's
/// AccumulatorSink, without adding that dependency).
class AccumulatorSink<T> implements Sink<T> {
  final List<T> events = <T>[];

  @override
  void add(T event) => events.add(event);

  @override
  void close() {}
}
