#!/usr/bin/env bash
# dist_test: prints the one entry point every distributed integration test is
# built into (integration_test/.dist/entry.dart, git-ignored), from
# tool/test_flow/dist_itests.json. Run from fushi/.
#
# One build per machine and run instead of one per file: `flutter test -d`
# builds each file from a fresh temporary listener, so nothing was reused and
# every file paid a full kernel compile + native build (45 s on the M4 Mac,
# 80-130 s on Windows, for tests of 5-30 s). The entry imports them all and
# FUSHI_DIST_ITEST picks the one a launch runs, so every file still gets a
# process and a data root of its own.
set -euo pipefail
manifest=tool/test_flow/dist_itests.json
files=$(grep -oE '"integration_test/[A-Za-z0-9_./-]+_test\.dart"' "$manifest" |
  tr -d '"' | LC_ALL=C sort -u)

echo "// Generated by tool/dist_test/itest_entry.sh from $manifest; do not edit."
echo "import 'dart:io';"
echo
i=0
for f in $files; do
  echo "import '../${f#integration_test/}' as t$i;"
  i=$((i + 1))
done
echo
echo "void main() {"
echo "  final String file = Platform.environment['FUSHI_DIST_ITEST'] ?? '';"
echo "  final Function? test = <String, Function>{"
i=0
for f in $files; do
  echo "    '$f': t$i.main,"
  i=$((i + 1))
done
echo "  }[file];"
echo "  if (test == null) {"
echo "    throw StateError('FUSHI_DIST_ITEST=\"\$file\" is not in this build');"
echo "  }"
echo "  Function.apply(test, const <Object?>[]);"
echo "}"
