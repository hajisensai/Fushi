// Runs one heavy command under the machine-wide lease (test_flow/heavy_lease.dart):
//
//   dart run tool/heavy.dart [--wait-max-min=0] [--max-minutes=120]
//                            [--cap-mb=N] [--here] [--check-only]
//                            -- <command...>
//   dart run tool/heavy.dart --status
//
//   e.g. dart run tool/heavy.dart -- flutter test test/foo_test.dart --no-pub
//        dart run tool/heavy.dart -- flutter analyze --no-pub
//        dart run tool/heavy.dart -- .\gradlew.bat :app:assembleRelease
//
// It queues first come, first served for a free slot whose run's memory
// ceiling fits the budget next to the holders' (half the RAM; it never "runs
// anyway", never reads the live free memory, and unless --wait-max-min=N is
// given it never gives up waiting; a run goes ahead of earlier ones only
// while those do not fit the budget and the head's booking stays free, and
// the same command submitted again from the same directory takes the queued
// one's place), keeps one build/-writing run per worktree, gives a
// `flutter test` without its own --concurrency a default of 4, and on
// Windows runs the command
// tree at below-normal priority under a memory ceiling, killing whatever the
// command leaves behind when it ends. A bare flutter / dart is resolved like
// the other repo tools (FUSHI_FLUTTER, FLUTTER_ROOT, the SDK running this
// script, PATH) and refused before queueing when that SDK is not the
// fushi/.fvmrc version (test_flow/heavy_sdk_check.dart). Exit code: the
// command's; 2 for a mismatched SDK; 75 when an
// explicit --wait-max-min ran out before admission; 79 when the same command
// was submitted again from this directory and took this run's place in the
// queue; 124 when --max-minutes cut it off. CI / FUSHI_HEAVY=off
// run the command directly.
//
// Before queueing here, the work goes to the other machines of the dist_test
// worker config (FUSHI_DIST_CONFIG, else fushi/tool/dist_test/
// workers.local.json) through tool/dist_test.dart when it may
// (test_flow/heavy_offload.dart): a `flutter test` (also `--coverage`, merged
// back here) of the app from fushi/, a `flutter test` / `dart test` of a
// package from packages/<name>/, a `flutter analyze` from fushi/, and with
// --check-only a compile check (`flutter build apk|appbundle|windows|macos`
// from fushi/, `gradlew :app:assemble*` from fushi/android/) whose output is
// not wanted here. Its output and exit code are then dist_test's (`DIST TEST
// VERDICT` / `DIST ANALYZE` / `DIST BUILD` last lines). When no other machine
// takes it, or dist_test cannot get going (bad worker config, no snapshot:
// exit 75 with a `DIST OFFLOAD: declined:` line), it runs here as before; a
// compile check that was red elsewhere is built here once more, since that
// machine's toolchain may be the cause. --max-minutes is dist_test's own
// deadline there (remote run killed, worker released, 124), Ctrl-C likewise
// (130). The Job Object below is joined first, so all of it is throttled.
// `--here` or FUSHI_HEAVY_OFFLOAD=off keep it here.
//
// When the other machines were only busy for now (dist_test exit 76:
// locked by other runs, paused, unreachable, short of memory), the run
// queues here and keeps asking them every minute while it waits
// (test_flow/heavy_offload_rival.dart): a free slot here or a worker there,
// whichever comes first, takes it -- one claim file settles the race, the
// loser lets go -- and a run taken there leaves the queue here.
//
// A command that runs here from inside fushi/ and compiles the app (flutter
// analyze / test / build / run, dart analyze / test / run / <script>.dart,
// gradlew) first gets the untracked lib/i18n/strings.g.dart regenerated by
// tool/gen_i18n.dart with the command's own SDK (stamped: a hash and exit
// when nothing changed); a failed generation fails the run with its exit code.
import 'dart:async';
import 'dart:convert';
import 'dart:io';

import 'test_flow/dist_plan.dart' show kDistOffloadDeclined;
import 'test_flow/heavy_budget.dart';
import 'test_flow/heavy_i18n.dart';
import 'test_flow/heavy_lease.dart';
import 'test_flow/heavy_offload.dart';
import 'test_flow/heavy_offload_rival.dart';
import 'test_flow/heavy_sdk_check.dart';
import 'test_flow/heavy_test_closure.dart';

Future<void> main(List<String> args) async {
  if (args.contains('--status')) return _status();
  final int sep = args.indexOf('--');
  if (sep < 0 || sep == args.length - 1) {
    stderr.writeln(
      'usage: dart run tool/heavy.dart [options] -- <command...>\n'
      '       dart run tool/heavy.dart --status',
    );
    exit(64);
  }
  final List<String> own = args.sublist(0, sep);
  final String? checkout = locateCheckoutRoot();
  final HeavySdkCheck sdk = checkHeavyCommandSdk(
    args.sublist(sep + 1),
    pinned: checkout == null ? null : readPinnedFlutterVersion(checkout),
  );
  if (sdk.error != null) {
    stderr.writeln(sdk.error);
    exit(2);
  }
  final List<String> asTyped = withDefaultTestConcurrency(sdk.command);
  final HeavyNeed classified = classifyHeavyCommand(asTyped);
  final _TestPlan? testPlan = classified.kind == HeavyKind.test
      ? _testPlan(asTyped)
      : null;
  // What runs here: a flutter test whose files never reach dart:ui runs as
  // `dart test` (one VM, no flutter_tools; heavy_budget.dart
  // dartTestCommandFor). The other machines still get the command as typed.
  final List<String> command = testPlan?.local ?? asTyped;
  final int? capOverride = _intArg(own, '--cap-mb=');
  final HeavyNeed need = HeavyNeed(
    kind: classified.kind,
    capMb: capOverride ?? classified.capMb,
    // An explicit --cap-mb books what it asks for; a test books from what it
    // compiles (heavy_budget.dart testBookMb).
    bookMb: capOverride ?? testPlan?.bookMb ?? classified.bookMb,
    worktreeExclusive: classified.worktreeExclusive,
    light: classified.light,
  );
  final int waitMax = _intArg(own, '--wait-max-min=') ?? 0;
  final int maxMinutes = _intArg(own, '--max-minutes=') ?? 120;
  final String label = command.take(3).join(' ');
  // The same command from the same directory is one run: submitted again
  // while it still queues here, it takes the queued one's place.
  final String runKey = heavyRunKey(
    cwd: Directory.current.absolute.path,
    argv: sdk.command,
  );

  // Joined before anything starts: the offloaded run (dist_test and its own
  // local fallback worker) and a run here after it declined both live in this
  // Job (below-normal priority, memory ceiling, whatever is left killed when
  // this process ends), as a run that never tried the other machines would.
  final HeavyJob? job = joinHeavyJob(
    need.capMb,
    log: (String l) => stderr.writeln(l),
  );

  _OffloadTarget? offload = own.contains('--here') || checkout == null
      ? null
      // Planned from the command as typed: the default --concurrency above
      // is this machine's, while an explicit -j caps the other machines too.
      : _offloadTarget(
          sdk.command,
          checkout: checkout,
          checkOnly: own.contains('--check-only'),
        );
  if (offload != null) {
    final int code = await _askElsewhere(offload, maxMinutes: maxMinutes);
    switch (heavyOffloadNext(code, offload.plan.kind)) {
      case HeavyOffloadNext.done:
        exit(code);
      case HeavyOffloadNext.runHere:
        _sayRunHere(code, offload.plan.kind);
        offload = null;
      case HeavyOffloadNext.askAgain:
        stderr.writeln(
          'heavy: the other machines are busy for now; queueing here and '
          'asking them again every ${kHeavyOffloadAskEvery.inSeconds} s '
          'until a slot here or a worker there takes it',
        );
    }
  }

  // Runs here: strings.g.dart is not tracked, so a checkout / merge since the
  // last run may have deleted or outdated it (test_flow/heavy_i18n.dart).
  if (checkout != null &&
      heavyCommandNeedsI18n(
        command,
        cwd: Directory.current.absolute.path,
        checkout: checkout,
        isWindows: Platform.isWindows,
      )) {
    final int gen = await _genI18n(command, checkout);
    if (gen != 0) {
      stderr.writeln(
        'heavy: fushi/tool/gen_i18n.dart failed (exit $gen); not running '
        '$label against a missing / stale lib/i18n/strings.g.dart',
      );
      exit(gen);
    }
  }

  // Queue here; while the other machines are only busy, keep asking them
  // (the rival): a slot here or a worker there, whichever comes first.
  HeavyLease? admitted;
  HeavyOffloadRival? rival;
  while (admitted == null) {
    final _OffloadTarget? target = offload;
    final HeavyOffloadRival? asking = target == null
        ? null
        : _rivalFor(target, maxMinutes: maxMinutes);
    rival = asking;
    // Ctrl-C while queued with an attempt out: let dist_test release what
    // it locked there before this process goes.
    final StreamSubscription<ProcessSignal>? onCtrlC = asking == null
        ? null
        : ProcessSignal.sigint.watch().listen((_) async {
            await asking.close();
            exit(130);
          });
    try {
      admitted = await acquireHeavyLease(
        need: need,
        label: label,
        worktreeRoot: checkout,
        waitMax: waitMax > 0 ? Duration(minutes: waitMax) : null,
        rival: asking,
        runKey: runKey,
      );
    } on HeavyLeaseSuperseded catch (e) {
      // The same command was submitted again from here and has this run's
      // place in the queue. Unless an attempt there took it meanwhile, the
      // claim here keeps any attempt still out from starting it as well.
      if (asking == null || asking.claimHere()) {
        await onCtrlC?.cancel();
        await asking?.close();
        stderr.writeln('$e. Not running it here.');
        exit(kHeavySupersededExit);
      }
    } on HeavyLeaseTimeout catch (e) {
      // Not admitted in time. Unless an attempt there took it meanwhile, the
      // claim here keeps any attempt still out from starting it.
      if (asking == null || asking.claimHere()) {
        await onCtrlC?.cancel();
        await asking?.close();
        stderr.writeln(e.message);
        exit(75);
      }
    } on HeavyLeaseWithdrawn {
      // Taken there: followed below.
    }
    await onCtrlC?.cancel();
    if (admitted != null) break;
    final _DistAttempt there = asking!.taken! as _DistAttempt;
    stderr.writeln(
      'heavy: another machine took $label while it queued here; '
      'following that run',
    );
    final int code = await there.follow(maxMinutes: maxMinutes);
    await asking.close();
    switch (heavyOffloadNext(code, target!.plan.kind)) {
      case HeavyOffloadNext.done:
        exit(code);
      case HeavyOffloadNext.runHere:
        _sayRunHere(code, target.plan.kind);
        offload = null;
      case HeavyOffloadNext.askAgain:
        stderr.writeln(
          'heavy: that machine turned it down after all (busy); queueing '
          'here again',
        );
    }
  }
  final HeavyLease lease = admitted;

  final Stopwatch ran = Stopwatch()..start();
  final Process p;
  try {
    p = await Process.start(
      command.first,
      command.skip(1).toList(),
      runInShell: Platform.isWindows,
      mode: ProcessStartMode.inheritStdio,
      environment: lease.childEnvironment,
    );
  } on ProcessException catch (e) {
    lease.release();
    stderr.writeln('heavy: cannot start ${command.first}: ${e.message}');
    exit(127);
  }
  bool cut = false;
  final Timer? limit = maxMinutes <= 0
      ? null
      : Timer(Duration(minutes: maxMinutes), () {
          cut = true;
          stderr.writeln(
            'heavy: $label still running after $maxMinutes min; '
            'killing it',
          );
          _killTree(p);
        });
  final int code = await p.exitCode;
  limit?.cancel();
  ran.stop();
  lease.release();
  // An attempt still out lost the claim to this machine and backs out by
  // itself; it must not be cut off holding a remote checkout lock.
  await rival?.close();

  final int? peak = job?.peakMb();
  stderr.writeln(
    'heavy: $label -> exit $code'
    '${lease.skipReason != null ? ' (no lease: ${lease.skipReason})' : ', slot ${lease.slot}'}'
    ', waited ${lease.waited.inSeconds} s, ran ${ran.elapsed.inSeconds} s'
    '${peak != null ? ', peak $peak MB of ${need.capMb} MB cap' : ''}',
  );
  if (peak != null && heavyCapHit(peak, need.capMb)) {
    stderr.writeln(
      'heavy: MEMORY CAP HIT -- failures in this run can come '
      'from the ${need.capMb} MB ceiling, not from the code. Narrow the run '
      '(fewer files, lower --concurrency) or raise --cap-mb.',
    );
  }
  exit(cut ? 124 : code);
}

/// Where heavy.dart hands its command to tool/dist_test.dart.
typedef _OffloadTarget = ({HeavyOffload plan, String config, String appDir});

/// How [command] may go to the other machines (test_flow/heavy_offload.dart),
/// or null when it is to run here (not offloadable, offloading off, no
/// worker config).
_OffloadTarget? _offloadTarget(
  List<String> command, {
  required String checkout,
  required bool checkOnly,
}) {
  final Map<String, String> env = Platform.environment;
  if (heavyLeaseSkipReason(env) != null || heavyOffloadDisabled(env)) {
    return null;
  }
  final String cwd = Directory.current.absolute.path.replaceAll(r'\', '/');
  final String? where = heavyOffloadWhere(cwd, checkout);
  final String appDir =
      '${Directory(checkout).absolute.path.replaceAll(r'\', '/')}/fushi';
  if (where == null || !File('$appDir/tool/dist_test.dart').existsSync()) {
    return null;
  }
  final HeavyOffload? plan = planHeavyOffload(
    command,
    where: where,
    cwd: cwd,
    checkOnly: checkOnly,
    exists: (String p) =>
        FileSystemEntity.typeSync('$cwd/$p') != FileSystemEntityType.notFound,
  );
  if (plan == null) return null;
  final String? config = heavyOffloadConfig(env, appDir);
  if (config == null) {
    final String? named = env['FUSHI_DIST_CONFIG'];
    if (named != null && named.isNotEmpty) {
      stderr.writeln(
        'heavy: FUSHI_DIST_CONFIG=$named does not exist; running it here',
      );
    }
    return null;
  }
  return (plan: plan, config: config, appDir: appDir);
}

/// Where this process's claim files go.
Directory get _claimDir => Directory('${heavyStateDir().path}/offload');

/// The first attempt, before queueing here: dist_test's output straight to
/// this console; its exit code (heavyOffloadNext says what it means).
Future<int> _askElsewhere(_OffloadTarget t, {required int maxMinutes}) async {
  stderr.writeln(
    'heavy: handing this ${t.plan.kind.name} to the other machines '
    '(tool/dist_test.dart ${t.plan.distArgs.join(' ')}); --here or '
    'FUSHI_HEAVY_OFFLOAD=off keeps it on this machine',
  );
  _claimDir.createSync(recursive: true);
  final HeavyOffloadClaim claim = HeavyOffloadClaim(
    '${_claimDir.path}/$pid-first.claim',
  )..delete(); // a dead process's leftover under a reused pid
  final _DistAttempt a = _DistAttempt(
    t,
    claim: claim,
    maxMinutes: maxMinutes,
    echo: true,
  );
  final int code = await a.follow(maxMinutes: maxMinutes);
  claim.delete();
  return code;
}

/// Asks the other machines again every [kHeavyOffloadAskEvery] while the
/// run waits here.
HeavyOffloadRival _rivalFor(_OffloadTarget t, {required int maxMinutes}) {
  String? lastReason;
  return HeavyOffloadRival(
    claims: _claimDir,
    log: (String l) => stderr.writeln(l),
    ask: (HeavyOffloadClaim claim) {
      final _DistAttempt a = _DistAttempt(
        t,
        claim: claim,
        maxMinutes: maxMinutes,
        echo: false,
      );
      // One line when the answer changes, not dist_test's whole output.
      unawaited(
        a.exitCode.then((int code) {
          if (claim.takenByOther || claim.mine) return;
          final String reason = a.reason ?? 'dist_test exit $code';
          if (reason != lastReason) {
            stderr.writeln('heavy: still queued here; other machines: $reason');
            lastReason = reason;
          }
        }),
      );
      return a;
    },
  )..start();
}

void _sayRunHere(int code, HeavyOffloadKind kind) {
  stderr.writeln(
    kind == HeavyOffloadKind.build && code != kDistOffloadDeclined
        // Another machine's SDK / NDK / Visual Studio is not this one's: a
        // red compile check there is only taken as red once it is red here.
        ? 'heavy: the compile check was red on another machine (exit $code); '
              'building here to tell the code from that machine\'s toolchain'
        : 'heavy: dist_test did not run it elsewhere (the DIST OFFLOAD line '
              'above says why); running it here',
  );
}

/// One tool/dist_test.dart run bound to a claim file. [echo]: its output
/// goes straight to this console (the first attempt); otherwise it is held
/// back until [follow] (taken there) and dropped when nobody took it.
class _DistAttempt implements HeavyOffloadAttempt {
  _DistAttempt(
    _OffloadTarget t, {
    required HeavyOffloadClaim claim,
    required int maxMinutes,
    required this.echo,
  }) {
    unawaited(_start(t, claim, maxMinutes));
  }

  final bool echo;
  final Stopwatch _age = Stopwatch()..start();
  final Completer<int> _code = Completer<int>();
  Process? _process;
  bool _following = false;
  final List<(IOSink, List<int>)> _held = <(IOSink, List<int>)>[];
  final StringBuffer _out = StringBuffer();

  @override
  Future<int> get exitCode => _code.future;

  /// The last `DIST OFFLOAD` line of a held-back run.
  String? get reason {
    String? last;
    for (final String l in _out.toString().split('\n')) {
      if (l.startsWith('DIST OFFLOAD')) last = l.trim();
    }
    return last;
  }

  Future<void> _start(
    _OffloadTarget t,
    HeavyOffloadClaim claim,
    int maxMinutes,
  ) async {
    final Process p;
    try {
      p = await Process.start(
        Platform.resolvedExecutable,
        <String>[
          'tool/dist_test.dart',
          '--config=${t.config}',
          '--offload-claim=${claim.path}',
          // dist_test keeps the deadline itself: it kills the remote run and
          // releases the worker's checkout before exiting 124.
          if (maxMinutes > 0) '--max-minutes=$maxMinutes',
          ...t.plan.distArgs,
        ],
        workingDirectory: t.appDir,
        mode: echo ? ProcessStartMode.inheritStdio : ProcessStartMode.normal,
      );
    } on ProcessException catch (e) {
      stderr.writeln('heavy: cannot start dist_test (${e.message})');
      _code.complete(kDistOffloadDeclined);
      return;
    }
    _process = p;
    if (echo) {
      _code.complete(await p.exitCode);
      return;
    }
    final Future<void> out = p.stdout.listen((List<int> d) {
      _out.write(utf8.decode(d, allowMalformed: true));
      _pass(stdout, d);
    }).asFuture<void>();
    final Future<void> err = p.stderr
        .listen((List<int> d) => _pass(stderr, d))
        .asFuture<void>();
    final int code = await p.exitCode;
    await Future.wait(<Future<void>>[out, err]);
    _code.complete(code);
  }

  void _pass(IOSink sink, List<int> data) {
    if (_following) {
      sink.add(data);
    } else if (_held.length < 20000) {
      _held.add((sink, data));
    }
  }

  /// Shows this run's output from its start and waits for it, as heavy.dart
  /// always waited for an offloaded run: Ctrl-C reaches dist_test too (same
  /// console / process group), which kills the remote run and releases the
  /// worker before it exits. Its exit code; 124 past --max-minutes, 130
  /// after Ctrl-C.
  Future<int> follow({required int maxMinutes}) async {
    _following = true;
    for (final (IOSink sink, List<int> data) in _held) {
      sink.add(data);
    }
    _held.clear();
    bool interrupted = false;
    final List<StreamSubscription<ProcessSignal>> signals =
        <StreamSubscription<ProcessSignal>>[
          ProcessSignal.sigint.watch().listen((_) {
            interrupted = true;
            if (!Platform.isWindows) _process?.kill(ProcessSignal.sigint);
          }),
          if (!Platform.isWindows)
            ProcessSignal.sigterm.watch().listen((_) {
              interrupted = true;
              _process?.kill(ProcessSignal.sigint);
            }),
        ];
    // Only a backstop for a dist_test that does not stop by itself at
    // --max-minutes (its own deadline cleans up; this kill cannot).
    bool cut = false;
    final Duration left =
        Duration(minutes: maxMinutes) + kHeavyOffloadStopGrace - _age.elapsed;
    final Timer? limit = maxMinutes <= 0
        ? null
        : Timer(left.isNegative ? Duration.zero : left, () {
            final Process? p = _process;
            if (p == null) return;
            cut = true;
            stderr.writeln(
              'heavy: offloaded run did not stop by itself '
              '${kHeavyOffloadStopGrace.inMinutes} min after its '
              '$maxMinutes min limit; killing it (the remote run may go on '
              'until its own timeout)',
            );
            _killTree(p);
          });
    final int code = await exitCode;
    limit?.cancel();
    for (final StreamSubscription<ProcessSignal> s in signals) {
      await s.cancel();
    }
    if (cut) return 124;
    if (interrupted) return 130;
    return code;
  }
}

/// Runs fushi/tool/gen_i18n.dart (stamped: a no-op when nothing changed) with
/// the SDK of [command]; its exit code.
Future<int> _genI18n(List<String> command, String checkout) async {
  final String dart = heavyI18nDart(
    command,
    checkout: checkout,
    fallback: Platform.resolvedExecutable,
    isWindows: Platform.isWindows,
  );
  try {
    final Process p = await Process.start(dart, <String>[
      '$checkout/fushi/tool/gen_i18n.dart',
    ], mode: ProcessStartMode.inheritStdio);
    return await p.exitCode;
  } on ProcessException catch (e) {
    stderr.writeln('heavy: cannot start $dart: ${e.message}');
    return 127;
  }
}

void _killTree(Process p) {
  if (Platform.isWindows) {
    Process.runSync('taskkill', <String>['/PID', '${p.pid}', '/T', '/F']);
  } else {
    p.kill(ProcessSignal.sigkill);
  }
}

void _status() {
  final MemorySnapshot? m = readMemorySnapshot();
  final int slots = heavySlotCount(m);
  final Directory dir = heavyStateDir()..createSync(recursive: true);
  final List<HeavyHolder> holders = readHeavyHolders(dir, slots);
  final int ours = holders.where((HeavyHolder h) => h.slot < slots).length;
  final int light = holders
      .where(
        (HeavyHolder h) =>
            h.slot >= kLightSlotBase &&
            h.slot < kLightSlotBase + kLightSlotCount,
      )
      .length;
  final int beyond = holders.length - ours - light;
  stdout.writeln(
    'heavy: $ours/$slots slots busy, $light/$kLightSlotCount light (analyze)'
    '${beyond > 0 ? ' (+$beyond past this slot count, booked below)' : ''}'
    ' (${dir.path})',
  );
  final int? budget = heavyBudgetMb(m);
  if (budget != null) {
    final int booked = holders.fold(
      0,
      (int a, HeavyHolder h) => a + h.bookedMb,
    );
    stdout.writeln('  memory budget: $booked / $budget MB booked');
  }
  if (m != null) {
    stdout.writeln(
      '  RAM available ${m.availPhysMb} / ${m.totalPhysMb} MB'
      '${m.availCommitMb != null ? '; commit headroom ${m.availCommitMb} MB' : ''}',
    );
  }
  final int now = DateTime.now().millisecondsSinceEpoch;
  final List<HeavyQueued> queue = readHeavyQueue(dir, sweep: false);
  stdout.writeln('  queue: ${queue.length} waiting');
  for (int i = 0; i < queue.length; i++) {
    final int? books = queue[i].bookedMb;
    stdout.writeln(
      '    ${i + 1}. pid ${queue[i].pid}, ${queue[i].label}'
      '${books == null ? '' : ', $books MB'}',
    );
  }
  for (final HeavyHolder h in holders) {
    stdout.writeln(
      '  slot ${h.slot}: pid ${h.pid}, ${h.label}, ${h.bookedMb} MB, '
      '${((now - h.startedAtMs) / 60000).toStringAsFixed(1)} min, '
      '${h.cwd}',
    );
  }
}

/// How a test command runs here and what it books.
typedef _TestPlan = ({int bookMb, List<String> local});

/// What a test [command] books (its import closure and tester count,
/// heavy_budget.dart testBookMb) and the command that runs here: `dart test`
/// when every target's closure stays off dart:ui, else [command] itself.
/// Whole-directory runs, unreadable targets and a failing closure walk book
/// the ceiling and run as typed.
_TestPlan _testPlan(List<String> command) {
  final List<String>? targets = testTargetsOf(command);
  TestClosure? closure;
  if (targets != null) {
    try {
      closure = testClosureOf(
        Directory.current.path,
        targets,
        edgeCache: File('${heavyStateDir().path}/closure-edges-v2.json'),
      );
    } on Object catch (e) {
      stderr.writeln(
        'heavy: import closure not measured ($e); booking the ceiling',
      );
    }
  }
  final String exe = command.first
      .replaceAll(r'\', '/')
      .split('/')
      .last
      .toLowerCase();
  List<String> local = command;
  bool flutter = !exe.startsWith('dart');
  if (flutter && closure != null && !closure.needsFlutter) {
    final List<String>? dart = dartTestCommandFor(command);
    if (dart != null) {
      stderr.writeln(
        'heavy: no target reaches dart:ui; running it as dart test '
        '(one VM, no flutter_tools)',
      );
      local = dart;
      flutter = false;
    }
  }
  final int concurrency = testConcurrencyOf(command) ?? kDefaultTestConcurrency;
  final int testers = targets == null
      ? concurrency
      : (targets.length < concurrency ? targets.length : concurrency);
  return (
    bookMb: testBookMb(
      closureFiles: closure?.files,
      testers: testers,
      flutter: flutter,
    ),
    local: local,
  );
}

int? _intArg(List<String> args, String prefix) {
  for (final String a in args) {
    if (a.startsWith(prefix)) return int.tryParse(a.substring(prefix.length));
  }
  return null;
}
