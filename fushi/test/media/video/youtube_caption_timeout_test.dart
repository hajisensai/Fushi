// gap-remote-9：YouTube 字幕轨表与 cue 下载此前没有任何响应超时。
//
// 两处都在起播之后异步跑，不挡首帧；但某个 client / timedtext 连上后被拖住（tarpit）
// 时 Future 永不完成：字幕轨列表永远不出现（字幕链挂死在那个 client 上，后面能出轨表
// 的 client 轮不到），或选中的字幕轨一直停在「加载中」。
import 'dart:async';
import 'dart:convert';

import 'package:http/http.dart' as http;
import 'package:http/testing.dart';
import 'package:test/test.dart';
import 'package:youtube_explode_dart/youtube_explode_dart.dart' as yt;

import 'package:fushi_audio/fushi_audio_core.dart' show AudioCue;
import 'package:fushi_engine/media/video/youtube_source_resolver.dart';

const String _videoId = 'dQw4w9WgXcQ';
const String _captionUrl =
    'https://www.youtube.com/api/timedtext?v=dQw4w9WgXcQ&lang=ja';

String _playerWithCaptions() => jsonEncode(<String, Object?>{
  'playabilityStatus': <String, Object?>{'status': 'OK'},
  'videoDetails': <String, Object?>{'videoId': _videoId},
  'captions': <String, Object?>{
    'playerCaptionsTracklistRenderer': <String, Object?>{
      'captionTracks': <Object?>[
        <String, Object?>{
          'baseUrl': _captionUrl,
          'name': <String, Object?>{'simpleText': '日本語'},
          'vssId': '.ja',
          'languageCode': 'ja',
        },
      ],
    },
  },
});

const String _json3 =
    '{"events":[{"tStartMs":1000,"dDurationMs":2000,'
    '"segs":[{"utf8":"こんにちは"}]}]}';

/// youtube_explode 校验响应时读 `response.request!`，MockClient 默认不填，这里补上。
yt.YoutubeHttpClient _client(
  Future<http.Response> Function(http.Request) handler,
) => yt.YoutubeHttpClient(
  MockClient((http.Request req) async {
    final http.Response r = await handler(req);
    return http.Response.bytes(
      r.bodyBytes,
      r.statusCode,
      headers: <String, String>{
        'content-type': 'application/json; charset=utf-8',
        ...r.headers,
      },
      request: req,
    );
  }),
);

String? _playerClientName(http.Request req) {
  if (req.url.path != '/youtubei/v1/player') return null;
  final Map<String, dynamic> client =
      ((jsonDecode(req.body) as Map<String, dynamic>)['context']
              as Map<String, dynamic>)['client']
          as Map<String, dynamic>;
  return client['clientName'] as String?;
}

const YoutubeCaptionTrack _track = YoutubeCaptionTrack(
  baseUrl: _captionUrl,
  languageCode: 'ja',
  languageName: '日本語',
  isAutoGenerated: false,
);

void main() {
  group('字幕轨表（单 client）', () {
    test('正常应答：拿到轨表（注入通路本身是通的）', () async {
      final List<YoutubeCaptionTrack> tracks =
          await fetchYoutubeCaptionTracksWithClient(
            _videoId,
            yt.YoutubeApiClient.android,
            httpClient: _client(
              (http.Request _) async =>
                  http.Response.bytes(utf8.encode(_playerWithCaptions()), 200),
            ),
          );
      expect(tracks.single.languageCode, 'ja');
      expect(tracks.single.baseUrl, _captionUrl);
    });

    test('对端连上不回：到上限返回空表，不抛、不无限等', () async {
      final List<YoutubeCaptionTrack> tracks =
          await fetchYoutubeCaptionTracksWithClient(
            _videoId,
            yt.YoutubeApiClient.androidVr,
            timeout: const Duration(milliseconds: 40),
            httpClient: _client(
              (http.Request _) => Completer<http.Response>().future,
            ),
          );
      expect(tracks, isEmpty);
    });

    test('字幕链：第一个 client 被拖住，超时后第二个 client 的轨表照样出来', () async {
      final List<String> asked = <String>[];
      Future<http.Response> handler(http.Request req) {
        final String? name = _playerClientName(req);
        if (name != null) asked.add(name);
        if (name == 'ANDROID_VR') return Completer<http.Response>().future;
        return Future<http.Response>.value(
          http.Response.bytes(utf8.encode(_playerWithCaptions()), 200),
        );
      }

      final List<YoutubeCaptionTrack> tracks =
          await fetchFirstNonEmptyByClient<YoutubeCaptionTrack>(
            <yt.YoutubeApiClient>[
              yt.YoutubeApiClient.androidVr,
              yt.YoutubeApiClient.android,
            ],
            (yt.YoutubeApiClient api) => fetchYoutubeCaptionTracksWithClient(
              _videoId,
              api,
              timeout: const Duration(milliseconds: 60),
              httpClient: _client(handler),
            ),
          );
      expect(tracks.single.languageCode, 'ja');
      expect(asked, containsAllInOrder(<String>['ANDROID_VR', 'ANDROID']));
    });
  });

  group('字幕 cue 下载', () {
    test('正常应答：解析出 cue', () async {
      final List<AudioCue> cues = await resolveYoutubeCaptionCues(
        _track,
        bookKey: 'yt:$_videoId',
        httpClient: _client(
          (http.Request req) async =>
              http.Response.bytes(utf8.encode(_json3), 200),
        ),
      );
      expect(cues.single.text, 'こんにちは');
    });

    test('对端连上不回：到上限返回空 cue（可重选重试），不无限等', () async {
      final List<AudioCue> cues = await resolveYoutubeCaptionCues(
        _track,
        bookKey: 'yt:$_videoId',
        timeout: const Duration(milliseconds: 40),
        httpClient: _client(
          (http.Request _) => Completer<http.Response>().future,
        ),
      );
      expect(cues, isEmpty);
    });
  });
}
