import 'dart:convert';

import 'package:drift/native.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:fushi_cli/fushi_cli.dart';
import 'package:fushi_core/fushi_core.dart';
import 'package:fushi_engine/media/video/video_book_repository.dart';
import 'package:fushi_engine/media/video/youtube_source_resolver.dart';

import 'package:fushi/src/media/video/video_import_dialog.dart'
    show StreamVideoUrlImporter;
import 'package:fushi/src/ops/ctl_url_import_routes.dart';

Matcher _status(int status) => throwsA(
  isA<CtlFailure>().having((CtlFailure f) => f.status, 'status', status),
);

const String _yt = 'https://www.youtube.com/watch?v=dQw4w9WgXcQ&t=5';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  late FushiDatabase db;
  late List<CtlRoute> routes;
  late List<String> captionLangs;
  bool enabled = true;
  bool readonly = false;
  bool failVariants = false;

  setUp(() {
    enabled = true;
    readonly = false;
    failVariants = false;
    captionLangs = <String>[];
    db = FushiDatabase.forTesting(NativeDatabase.memory());
    routes = buildUrlImportCtlRoutesFor(
      importer: () => StreamVideoUrlImporter(VideoBookRepository(db)),
      videoEnabled: () => enabled,
      isReadonly: () => readonly,
      youtube: UrlImportYoutubeProbe(
        metadata: (String url) async => const YoutubeMetadata(
          title: 'Never Gonna Give You Up',
          thumbnailUrl: 'https://i.ytimg.com/vi/dQw4w9WgXcQ/hqdefault.jpg',
        ),
        variants: (String url) async {
          if (failVariants) throw StateError('manifest timeout');
          return const YoutubeVariantSet(
            variants: <YoutubeVideoVariant>[
              YoutubeVideoVariant(
                height: 1080,
                label: '1080p',
                videoUrl: 'https://v/1080',
                codec: 'avc1',
              ),
              YoutubeVideoVariant(
                height: 720,
                label: '720p',
                videoUrl: 'https://v/720',
                codec: 'avc1',
              ),
            ],
            audioStreamUrl: 'https://a',
            defaultIndex: 0,
          );
        },
        captions: (String url, String lang) async {
          captionLangs.add(lang);
          return const <YoutubeCaptionTrack>[
            YoutubeCaptionTrack(
              baseUrl: 'https://c/ja',
              languageCode: 'ja',
              languageName: 'ja',
              isAutoGenerated: false,
            ),
            YoutubeCaptionTrack(
              baseUrl: 'https://c/en',
              languageCode: 'en',
              languageName: 'en',
              isAutoGenerated: true,
            ),
          ];
        },
      ),
    );
  });

  tearDown(() => db.close());

  Future<Object?> call(
    String method,
    String pattern, {
    Map<String, Object?> body = const <String, Object?>{},
  }) => routes
      .singleWhere((CtlRoute r) => r.method == method && r.pattern == pattern)
      .handler(CtlCall(method: method, path: pattern, body: body));

  Map<String, Object?> asMap(Object? v) => (v! as Map).cast<String, Object?>();

  test('YouTube 探测：标题、画质（默认档）、字幕轨，身份按 videoId 收敛', () async {
    final Map<String, Object?> probe = asMap(
      await call(
        'GET',
        '$kUrlImportCtlRoot/probe',
        body: <String, Object?>{'url': _yt, 'lang': 'ja'},
      ),
    );
    expect(probe['kind'], 'youtube');
    expect(probe['bookUid'], 'video/stream/yt:dQw4w9WgXcQ');
    expect(probe['title'], 'Never Gonna Give You Up');
    final List<Object?> qualities = probe['qualities']! as List<Object?>;
    expect(asMap(qualities.first)['label'], '1080p');
    expect(asMap(qualities.first)['default'], isTrue);
    expect(asMap(qualities.last).containsKey('default'), isFalse);
    final List<Object?> captions = probe['captions']! as List<Object?>;
    expect(asMap(captions.first)['label'], '日本語');
    expect(asMap(captions.last)['auto'], isTrue);
    expect(captionLangs, <String>['ja']);
    expect(probe.containsKey('errors'), isFalse);
  });

  test('探测分段 best-effort：画质取不到记进 errors，其余照常', () async {
    failVariants = true;
    final Map<String, Object?> probe = asMap(
      await call(
        'GET',
        '$kUrlImportCtlRoot/probe',
        body: <String, Object?>{'url': _yt},
      ),
    );
    expect(asMap(probe['errors'])['qualities'], contains('manifest timeout'));
    expect(probe['title'], isNotNull);
    expect(probe['captions'], isNotNull);
  });

  test('直链 / 网页站探测只给种类，不联网', () async {
    final Map<String, Object?> direct = asMap(
      await call(
        'GET',
        '$kUrlImportCtlRoot/probe',
        body: <String, Object?>{'url': 'https://cdn.example.com/a/movie.mp4'},
      ),
    );
    expect(direct['kind'], 'stream');
    expect(direct.containsKey('captions'), isFalse);
    final Map<String, Object?> page = asMap(
      await call(
        'GET',
        '$kUrlImportCtlRoot/probe',
        body: <String, Object?>{'url': 'https://www.bilibili.com/video/BV1'},
      ),
    );
    expect(page['kind'], 'webPage');
    expect(captionLangs, isEmpty);
  });

  test('导入直链：与对话框同一门面落库（字幕 / header 进 streamSpecJson），重复导入加后缀', () async {
    const String url = 'https://cdn.example.com/a/movie.mp4';
    final Map<String, Object?> imported = asMap(
      await call(
        'POST',
        kUrlImportCtlRoot,
        body: <String, Object?>{
          'url': url,
          'subtitleUrl': 'https://cdn.example.com/a/movie.vtt',
          'referer': 'https://example.com/',
        },
      ),
    );
    final String uid = imported['bookUid']! as String;
    expect(imported['key'], 'video:$uid');
    expect(imported['title'], 'movie');
    expect(imported['kind'], 'stream');
    final VideoBookRow row = (await VideoBookRepository(db).getByBookUid(uid))!;
    expect(row.videoPath, url);
    final Map<String, Object?> spec =
        jsonDecode(row.streamSpecJson!) as Map<String, Object?>;
    expect(spec.values, contains('https://cdn.example.com/a/movie.vtt'));
    expect(spec.values, contains('https://example.com/'));

    final Map<String, Object?> again = asMap(
      await call(
        'POST',
        kUrlImportCtlRoot,
        body: <String, Object?>{'url': url},
      ),
    );
    expect(again['bookUid'], isNot(uid));
    expect(await VideoBookRepository(db).listAll(), hasLength(2));
  });

  test('参数与门：非 http(s) 400、坏字幕地址 400、模块关闭 / 只读 422', () async {
    expect(
      () => call(
        'POST',
        kUrlImportCtlRoot,
        body: <String, Object?>{'url': 'file:///a.mp4'},
      ),
      _status(400),
    );
    expect(
      () => call(
        'POST',
        kUrlImportCtlRoot,
        body: <String, Object?>{
          'url': 'https://cdn.example.com/a.mp4',
          'subtitleUrl': 'C:\\a.srt',
        },
      ),
      _status(400),
    );
    expect(() => call('GET', '$kUrlImportCtlRoot/probe'), _status(400));
    readonly = true;
    expect(
      () => call(
        'POST',
        kUrlImportCtlRoot,
        body: <String, Object?>{'url': 'https://cdn.example.com/a.mp4'},
      ),
      _status(422),
    );
    enabled = false;
    expect(
      () => call(
        'GET',
        '$kUrlImportCtlRoot/probe',
        body: <String, Object?>{'url': _yt},
      ),
      _status(422),
    );
    expect(await VideoBookRepository(db).listAll(), isEmpty);
  });
}
