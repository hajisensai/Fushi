/// 凝彩的分镜清单与每种构图的纯数据（folia `types.ts` 的 `TEMPERA_SHOT_KINDS` +
/// `temperaShotProfiles.ts`）：歌词排在哪、字从哪飞进来、镜头怎么走、构图有多吵。
/// profile 数据由脚本从 folia 源码逐项转来，顺序与 folia 一致（编译期按下标挑选，顺序即确定性）。
library;

/// 排版对齐。
enum TemperaAlign { center, left, right }

/// 构图的「音量」：换气段只取安静构图，副歌不取安静构图。
enum TemperaMood { quiet, neutral, loud }

/// 歌词排版框（视口比例）。
class TemperaShotRegion {
  const TemperaShotRegion({
    required this.cx,
    required this.cy,
    required this.w,
    required this.h,
    this.align = TemperaAlign.center,
    this.rotation = 0,
    this.fontScale = 1,
  });

  final double cx;
  final double cy;
  final double w;
  final double h;
  final TemperaAlign align;
  final double rotation;

  /// 乘在分镜基础字号上。
  final double fontScale;
}

/// 一种构图的排版 / 入场 / 镜头 / 音量。
class TemperaShotProfile {
  const TemperaShotProfile({
    required this.region,
    required this.enterX,
    required this.enterY,
    required this.travel,
    required this.zoomStart,
    required this.zoomEnd,
    required this.mood,
    this.sharedDecor = true,
  });

  final TemperaShotRegion region;

  /// 字的基础入场向量（字号的倍数）。
  final double enterX;
  final double enterY;

  /// 镜头沿 flow 方向的行程与缩放。
  final double travel;
  final double zoomStart;
  final double zoomEnd;
  final TemperaMood mood;

  /// 是否叠共享的贯穿线与角落 motif（物语过场卡关掉）。
  final bool sharedDecor;
}

TemperaShotRegion _r(
  double cx,
  double cy,
  double w,
  double h, {
  TemperaAlign align = TemperaAlign.center,
  double rotation = 0,
  double fontScale = 1,
}) => TemperaShotRegion(
  cx: cx,
  cy: cy,
  w: w,
  h: h,
  align: align,
  rotation: rotation,
  fontScale: fontScale,
);

