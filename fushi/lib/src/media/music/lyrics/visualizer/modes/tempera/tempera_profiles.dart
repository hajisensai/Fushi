/// 某种构图的 profile（未知回落 duo-split）。
TemperaShotProfile temperaShotProfile(String kind) =>
    _profiles[kind] ?? _profiles['duo-split']!;

/// 这些音量允许的构图（保持清单顺序）。
List<String> temperaShotCandidates(List<TemperaMood> moods) {
  final List<String> out = temperaShotKinds
      .where((String k) => moods.contains(temperaShotProfile(k).mood))
      .toList();
  return out.isEmpty ? temperaShotKinds : out;
}
