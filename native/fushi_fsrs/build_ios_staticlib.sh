#!/usr/bin/env bash
# iOS 版 libfushi_fsrs.a（staticlib，**单独**一份）+ xcconfig 片段。
#
# 注意：这份单独的 .a **不能**与 fushi_fsrs 的 libfushi_fsrs.a 一起 -force_load 进 Runner——
# 两个 Rust staticlib 各自带一整份 Rust std / core / alloc，同时 -force_load 会撞重复符号
# （duplicate symbol _rust_eh_personality / __rdl_alloc …）。上架用的是伞形库
# native/fushi_ios_umbrella（一个 staticlib 同时导出 fp2p_* 与 ffsrs_*，std 只有一份），
# 切换步骤见 native/fushi_fsrs/README.md「iOS」。本脚本留给：只要 SRS、不要 P2P 的实验构建，
# 以及对单独这个 crate 跑 verify_abi.sh。
#
# 生成的 xcconfig 定义 FUSHI_FSRS_LDFLAGS = -force_load <.a> + rustc 报的系统库；
# fushi/ios 目前**没有** include 它（见 README），Dart 侧 `DynamicLibrary.process()` 取符号
# （packages/fushi_srs/lib/src/ffi/fushi_fsrs_library.dart）。
#
# 用法: build_ios_staticlib.sh [device|simulator|all]   缺省 all
#   device    : aarch64-apple-ios                        → prebuilt/ios/iphoneos/libfushi_fsrs.a
#   simulator : aarch64-apple-ios-sim + x86_64-apple-ios → prebuilt/ios/iphonesimulator/libfushi_fsrs.a（lipo）
# 前提: rustup target add aarch64-apple-ios aarch64-apple-ios-sim x86_64-apple-ios
#
# 部署目标与 fushi/ios/Runner.xcodeproj 的 IPHONEOS_DEPLOYMENT_TARGET 对齐（15.1）。
set -euo pipefail

WHICH="${1:-all}"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT_DIR="$SCRIPT_DIR/prebuilt/ios"
export IPHONEOS_DEPLOYMENT_TARGET="${IPHONEOS_DEPLOYMENT_TARGET:-15.1}"

cd "$SCRIPT_DIR"

# 编一个 target 的 staticlib，把 rustc 报出的「链接方还需要的系统库」写到 $2。
# 静态库自己不带链接指令（framework 依赖在最终链接 Runner 时才解析），所以必须把
# `--print native-static-libs` 的结论交给 Xcode；先 clean 本 crate 保证这次真的会
# 重新编译并打印（依赖 crate 的缓存不受影响）。
build_target() {
  local target="$1" libs_out="$2"
  local log
  log="$(mktemp)"
  cargo clean --release --target "$target" -p fushi_fsrs
  echo "==> cargo rustc --release --lib --target $target --crate-type staticlib (IPHONEOS_DEPLOYMENT_TARGET=$IPHONEOS_DEPLOYMENT_TARGET)"
  # --color never：CI 设了 CARGO_TERM_COLOR=always，rustc 的 note 行会带 ANSI 转义，
  # 抠出来的 `-lm` 变成 `-lm\e[0m`，Xcode 链接时报 Library 'm…' not found。
  cargo rustc --color never --release --lib --target "$target" --crate-type staticlib \
    -- --print native-static-libs 2>&1 | tee "$log"
  local libs
  libs="$(sed -n 's/.*native-static-libs: //p' "$log" | tail -n 1)"
  rm -f "$log"
  if [[ -z "$libs" ]]; then
    echo "rustc did not report native-static-libs for $target" >&2
    exit 1
  fi
  # 这串原样进 OTHER_LDFLAGS：只允许 -l<name> / -framework <name>，别的一律当场失败，
  # 而不是等 Xcode 链接时才冒出一个莫名其妙的库名。
  local prev="" tok
  for tok in $libs; do
    if [[ "$prev" == "-framework" ]]; then
      [[ "$tok" =~ ^[A-Za-z0-9_]+$ ]] || { echo "bad framework name in native-static-libs: $tok" >&2; exit 1; }
    elif [[ "$tok" != "-framework" && ! "$tok" =~ ^-l[A-Za-z0-9_+.-]+$ ]]; then
      echo "unexpected token in native-static-libs: $(printf '%q' "$tok")" >&2
      exit 1
    fi
    prev="$tok"
  done
  printf '%s\n' "$libs" > "$libs_out"
  [[ -f "target/$target/release/libfushi_fsrs.a" ]] || { echo "missing target/$target/release/libfushi_fsrs.a" >&2; exit 1; }
}

build_device() {
  local dir="$OUT_DIR/iphoneos"
  mkdir -p "$dir"
  build_target aarch64-apple-ios "$dir/native-static-libs.txt"
  cp "target/aarch64-apple-ios/release/libfushi_fsrs.a" "$dir/libfushi_fsrs.a"
  lipo -info "$dir/libfushi_fsrs.a"
}

build_simulator() {
  local dir="$OUT_DIR/iphonesimulator"
  mkdir -p "$dir"
  build_target aarch64-apple-ios-sim "$dir/.libs.arm64"
  build_target x86_64-apple-ios "$dir/.libs.x86_64"
  lipo -create \
    "target/aarch64-apple-ios-sim/release/libfushi_fsrs.a" \
    "target/x86_64-apple-ios/release/libfushi_fsrs.a" \
    -output "$dir/libfushi_fsrs.a"
  # 两个切片的系统库清单应当一致；直接拼起来——链接器对重复的 -l / -framework 无所谓，
  # 真有差异也不会漏链。
  echo "$(cat "$dir/.libs.arm64") $(cat "$dir/.libs.x86_64")" > "$dir/native-static-libs.txt"
  rm -f "$dir/.libs.arm64" "$dir/.libs.x86_64"
  lipo -info "$dir/libfushi_fsrs.a"
}

case "$WHICH" in
  device) build_device ;;
  simulator) build_simulator ;;
  all) build_device; build_simulator ;;
  *) echo "usage: build_ios_staticlib.sh [device|simulator|all]" >&2; exit 2 ;;
esac

# xcconfig 按「磁盘上实际存在的切片」生成，而不是只按本次编的：先编 simulator 再单编
# device 时，两个 SDK 都还能链接。
xc="$OUT_DIR/fushi_fsrs.xcconfig"
{
  echo "// Generated by native/fushi_fsrs/build_ios_staticlib.sh - do not edit (git-ignored)."
  echo "// Not included by fushi/ios yet: link native/fushi_ios_umbrella instead (see README)."
  echo 'FUSHI_FSRS_IOS_DIR = $(PROJECT_DIR)/../../native/fushi_fsrs/prebuilt/ios'
  for sdk in iphoneos iphonesimulator; do
    [[ -f "$OUT_DIR/$sdk/libfushi_fsrs.a" ]] || continue
    echo "FUSHI_FSRS_LDFLAGS[sdk=${sdk}*] = -force_load \"\$(FUSHI_FSRS_IOS_DIR)/$sdk/libfushi_fsrs.a\" $(cat "$OUT_DIR/$sdk/native-static-libs.txt")"
  done
} > "$xc"
echo "==> $xc"
cat "$xc"
