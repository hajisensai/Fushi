// The admitted body glyph helper returns the rendered scalar plus the bitmap
// dimensions used for the queued item. Runtime traces for WoH 1.0 prove the
// same width/height in both the glyph descriptor and the helper output, while
// render-item +0x18/+0x1c are only a one-pixel queue extent (x+1/y+1). They are
// therefore not the visible glyph bounds used by lookup hit testing.
inline constexpr size_t kBodyGlyphDescriptorWidthWord = 1u;
inline constexpr size_t kBodyGlyphDescriptorHeightWord = 2u;
inline constexpr size_t kBodyGlyphOutputScalarWord = 0u;
inline constexpr size_t kBodyGlyphOutputBitmapWidthWord = 21u;
inline constexpr size_t kBodyGlyphOutputBitmapHeightWord = 22u;
inline constexpr uint32_t kBodyGlyphMaximumExtent = 512u;

struct BodyGlyphMetricDiagnostic {
  uint32_t bitmap_width = 0u;
  uint32_t bitmap_height = 0u;
};

inline bool ReadBodyGlyphMetricDiagnostic(
    const uint32_t* descriptor_words, size_t descriptor_word_count,
    const uint32_t* output_words, size_t output_word_count,
    uint32_t raw_scalar, uint32_t consumed_utf16_width,
    uint32_t observed_scalar_width, BodyGlyphMetricDiagnostic* out) {
  if (descriptor_words == nullptr || output_words == nullptr || out == nullptr ||
      descriptor_word_count <= kBodyGlyphDescriptorHeightWord ||
      output_word_count <= kBodyGlyphOutputBitmapHeightWord ||
      raw_scalar == 0u || consumed_utf16_width == 0u ||
      consumed_utf16_width > 2u ||
      observed_scalar_width != consumed_utf16_width ||
      output_words[kBodyGlyphOutputScalarWord] != raw_scalar) {
    return false;
  }
  const uint32_t width = output_words[kBodyGlyphOutputBitmapWidthWord];
  const uint32_t height = output_words[kBodyGlyphOutputBitmapHeightWord];
  if (width == 0u || height == 0u || width > kBodyGlyphMaximumExtent ||
      height > kBodyGlyphMaximumExtent ||
      descriptor_words[kBodyGlyphDescriptorWidthWord] != width ||
      descriptor_words[kBodyGlyphDescriptorHeightWord] != height) {
    return false;
  }
  out->bitmap_width = width;
  out->bitmap_height = height;
  return true;
}

struct BodySubmitCallerFrameDiagnostic {
  uint32_t raw_scalar = 0u;
  uint32_t raw_utf16_index = 0u;
  uint32_t consumed = 0u;
  uintptr_t line_base = 0u;
};

inline bool ReadBodySubmitCallerFrameDiagnostic(
    const uint8_t* wrapper_return_slot, size_t readable_bytes,
    BodySubmitCallerFrameDiagnostic* out) {
  if (wrapper_return_slot == nullptr || out == nullptr ||
      readable_bytes < kBodySubmitCallerFrameReadBytes) {
    return false;
  }
  BodySubmitCallerFrameDiagnostic decoded;
  std::memcpy(&decoded.raw_scalar,
              wrapper_return_slot + kBodySubmitRawScalarStackOffset,
              sizeof(decoded.raw_scalar));
  std::memcpy(&decoded.raw_utf16_index,
              wrapper_return_slot + kBodySubmitRawUtf16IndexStackOffset,
              sizeof(decoded.raw_utf16_index));
  std::memcpy(&decoded.line_base,
              wrapper_return_slot + kBodySubmitLineBaseStackOffset,
              sizeof(decoded.line_base));
  std::memcpy(&decoded.consumed,
              wrapper_return_slot + kBodySubmitConsumedStackOffset,
              sizeof(decoded.consumed));
  *out = decoded;
  return true;
}

inline bool CopyBoundedNullTerminatedUtf16(
    const uint16_t* source, size_t max_units, uint16_t* destination,
    size_t destination_units, uint32_t* copied_units) {
  if (source == nullptr || destination == nullptr || copied_units == nullptr ||
      max_units == 0u || destination_units < max_units) {
    return false;
  }
  for (size_t index = 0u; index < max_units; ++index) {
    const uint16_t unit = source[index];
    if (unit == 0u) {
      *copied_units = static_cast<uint32_t>(index);
      return true;
    }
    destination[index] = unit;
  }
  return false;
}

inline uint64_t HashUtf16Units(const uint16_t* text, uint32_t units) {
  if (text == nullptr) return 0u;
  uint64_t value = 1469598103934665603ull;
  for (uint32_t index = 0u; index < units; ++index) {
    const uint16_t unit = text[index];
    value ^= static_cast<uint8_t>(unit & 0xffu);
    value *= 1099511628211ull;
    value ^= static_cast<uint8_t>(unit >> 8u);
    value *= 1099511628211ull;
  }
  return value;
}
