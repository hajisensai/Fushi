#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Offline generator: OpenCC STCharacters.txt -> opencc_st_data.{h,cpp}

One-shot vendoring tool. NOT part of the CMake build — the generated .h/.cpp are
checked into native/fushidicts/fushidicts_src/text_processor/ as ordinary sources.
Re-run only when bumping the upstream pin.

Source data: BYVoid/OpenCC (Apache-2.0) data/dictionary/STCharacters.txt.
Format of each line: `<simplified>\t<trad1> <trad2> ...` — we keep only the FIRST
candidate (single-char s2t is enough for headword fallback; the first candidate is
OpenCC's primary conversion). Entries whose key is not a single code point, or whose
first candidate is not a single code point, or equals the key, are skipped.

Usage:
  python tool/native_gen/gen_opencc_st.py <STCharacters.txt> <output_dir> <pin>
"""
from __future__ import annotations

import sys
from pathlib import Path


def main(argv: list[str]) -> int:
    if len(argv) != 4:
        print(__doc__)
        return 2
    src, out_dir, pin = Path(argv[1]), Path(argv[2]), argv[3]
    out_dir.mkdir(parents=True, exist_ok=True)

    mapping: dict[int, int] = {}
    skipped = 0
    for line in src.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        key, _, values = line.partition("\t")
        first = values.split(" ")[0] if values else ""
        if len(key) != 1 or len(first) != 1 or first == key:
            skipped += 1
            continue
        mapping.setdefault(ord(key), ord(first))
    pairs = sorted(mapping.items())

    head = [
        "// AUTO-GENERATED by tool/native_gen/gen_opencc_st.py — DO NOT EDIT.",
        f"// Source: BYVoid/OpenCC (Apache-2.0, pin {pin}) data/dictionary/STCharacters.txt.",
        "// Maps 简体 (simplified) -> 繁體 (traditional), first candidate only.",
        "// LICENSE for the data lives alongside: OPENCC_LICENSE.",
    ]
    (out_dir / "opencc_st_data.h").write_text(
        "\n".join(head + [
            "#pragma once",
            "",
            "#include <cstddef>",
            "",
            "namespace opencc_st {",
            "",
            "struct SimpToTrad {",
            "  char32_t simplified;",
            "  char32_t traditional;",
            "};",
            "",
            "// Flat, code-point-sorted simplified->traditional table.",
            "extern const SimpToTrad kSimpToTrad[];",
            "extern const std::size_t kSimpToTradCount;",
            "",
            "}  // namespace opencc_st",
            "",
        ]),
        encoding="utf-8",
    )
    body = head + [
        '#include "opencc_st_data.h"',
        "",
        "namespace opencc_st {",
        "",
        "const SimpToTrad kSimpToTrad[] = {",
    ]
    body += [f"    {{0x{s:04X}, 0x{t:04X}}}," for s, t in pairs]
    body += [
        "};",
        "",
        f"const std::size_t kSimpToTradCount = {len(pairs)};",
        "",
        "}  // namespace opencc_st",
        "",
    ]
    (out_dir / "opencc_st_data.cpp").write_text("\n".join(body), encoding="utf-8")
    print(f"wrote {len(pairs)} pairs (skipped {skipped})")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
